const assert = require('node:assert/strict');
const Session = require('../static/evaluation.js');
const s = new Session();
function trial(expected, labels) {
 s.start(expected,30,'test fixture');
 for (const label of labels) s.observe(label,label ? 'ok' : 'uncertain',20);
 return s.finish();
}
assert.equal(trial('A',['A','A','A',null,null]).outcome,'correct');
assert.equal(trial('I',['Y','Y','Y',null,null]).outcome,'wrong');
assert.equal(trial('C',['C','C',null,null,null]).outcome,'uncertain');
assert.equal(trial('NONE',[null,null,null,null,null]).outcome,'correct_rejection');
assert.equal(trial('NONE',['A','A','A',null,null]).outcome,'false_accept');
const r=s.report();
assert.equal(r.metrics.signTrials,3);assert.equal(r.metrics.accuracy,1/3);
assert.equal(r.metrics.coverage,2/3);assert.equal(r.metrics.acceptedAccuracy,1/2);
assert.equal(r.metrics.rejectionProbes,2);assert.equal(r.metrics.falseAccepts,1);
assert.equal(r.perLetter.I.predictions.Y,1);
s.start('A',30,'test fixture');s.cancel();assert.equal(s.trials.length,5);
s.start('A',30,'test fixture');assert.throws(()=>s.finish(),/Not enough/);
assert.equal(new Session().report().metrics.accuracy,null);
console.log('Evaluation outcome, abstention, rejection and cancellation checks passed');
const html=Session.readableEvaluation(s.report());
assert.ok(html.includes('ASL webcam evaluation'));
assert.ok(html.includes('Uncertain — no stable majority'));
assert.ok(html.includes('33.3%'));
const emptyHtml=Session.readableEvaluation(new Session().report());
assert.ok(emptyHtml.includes('Not available (no applicable trials)'));
console.log('Readable report checks passed');
assert.equal(s.progress().tested,3);
assert.equal(s.progress().counts.A,1);
assert.equal(s.progress().repeated,0);
assert.equal(s.nextLetter('A'),'B');
assert.equal(s.nextLetter('I'),'K');
assert.ok(!s.progress().untested.includes('J'));
assert.ok(!s.progress().untested.includes('Z'));
assert.ok(Session.readableEvaluation(s.report()).includes('Alphabet coverage: 3/24'));
console.log('Guided alphabet progress and readable coverage checks passed');
